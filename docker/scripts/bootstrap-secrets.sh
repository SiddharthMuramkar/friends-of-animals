#!/usr/bin/env bash
# Create the VPS database secrets under /etc/foa. Idempotent: an existing
# secret is never overwritten. Prints file names, never values.
#
#   /etc/foa                    0700 root
#   /etc/foa/secrets/*          0400; owner 999 (postgres in the Postgres image)
#                               or 6432 (pgbouncer) where a container reads them
#   /etc/foa/vercel-urls.env    0600 root: connection URLs for Vercel
#
# Random secrets: 32 bytes as hex (openssl rand -hex 32). Derived files
# (PgBouncer auth file, pgBackRest cipher conf, vercel-urls.env) are rebuilt
# from them on every run, so a deliberately rotated secret propagates.
#
# Usage: sudo bootstrap-secrets.sh
set -euo pipefail
umask 077

ROOT=/etc/foa
SECRETS="$ROOT/secrets"
HOST=db.shipped-it.dev
PORT=6432
PG_UID=999       # postgres in postgres:18.7-trixie
PGB_UID=6432     # pgbouncer in docker/pgbouncer/Dockerfile

if [ "$(id -u)" -ne 0 ]; then
  echo "bootstrap-secrets: run as root" >&2
  exit 1
fi
command -v openssl >/dev/null || { echo "bootstrap-secrets: openssl not found" >&2; exit 1; }

install -d -m 0700 -o root -g root "$ROOT" "$SECRETS" "$ROOT/lego"

# new_secret NAME OWNER BYTES: create $SECRETS/NAME with random hex if missing.
new_secret() {
  local owner=$2 bytes=${3:-32} path="$SECRETS/$1" tmp
  if [ -s "$path" ]; then
    chown "$owner:$owner" "$path"
    chmod 0400 "$path"
    echo "kept     $path"
    return
  fi
  tmp="$(mktemp "$SECRETS/.tmp.XXXXXX")"
  openssl rand -hex "$bytes" | tr -d '\n' >"$tmp"
  chown "$owner:$owner" "$tmp"
  chmod 0400 "$tmp"
  mv -f "$tmp" "$path"
  echo "created  $path"
}

# write_derived PATH OWNER MODE: replace PATH with stdin if the content differs.
write_derived() {
  local path=$1 owner=$2 mode=$3 tmp
  tmp="$(mktemp "$(dirname "$path")/.tmp.XXXXXX")"
  cat >"$tmp"
  chown "$owner" "$tmp"
  chmod "$mode" "$tmp"
  if [ -e "$path" ] && cmp -s "$tmp" "$path"; then
    rm -f "$tmp"
    chown "$owner" "$path"
    chmod "$mode" "$path"
    echo "kept     $path"
  else
    mv -f "$tmp" "$path"
    echo "wrote    $path"
  fi
}

secret() { cat "$SECRETS/$1"; }

# Postgres roles (read inside the containers as uid 999).
new_secret pg_prod_postgres_password "$PG_UID"
new_secret pg_prod_foa_migrator_password "$PG_UID"
new_secret pg_prod_foa_app_password "$PG_UID"
new_secret pg_nonprod_postgres_password "$PG_UID"
new_secret pg_nonprod_nonprod_migrator_password "$PG_UID"
new_secret pg_nonprod_nonprod_app_password "$PG_UID"
# One auth_user for both servers: PgBouncer has a single auth_file.
new_secret pgbouncer_auth_password "$PG_UID"
# pgBackRest repo1 cipher passphrase (48 random bytes). Losing it makes every
# backup unreadable: keep an offline copy. Only the derived conf below is
# mounted into a container.
new_secret pgbackrest_repo1_cipher_pass root 48

# PgBouncer auth_file: pgbouncer_auth only.
printf '"pgbouncer_auth" "%s"\n' "$(secret pgbouncer_auth_password)" |
  write_derived "$SECRETS/pgbouncer_userlist.txt" "$PGB_UID:$PGB_UID" 0400

# pgBackRest conf.d snippet, mounted into pg-prod.
printf '[global]\nrepo1-cipher-pass=%s\n' "$(secret pgbackrest_repo1_cipher_pass)" |
  write_derived "$SECRETS/pgbackrest_cipher.conf" "$PG_UID:$PG_UID" 0400

# Connection URLs for Vercel (host db.shipped-it.dev, PgBouncer 6432, TLS
# verify-full). Hex passwords need no URL encoding. DATABASE_URL uses the
# transaction pool; DIRECT_URL the migrator role (session pool). Previews
# replace the /foa_pr placeholder with foa_pr_<n> or foa_br_<slug>.
url() { printf 'postgres://%s:%s@%s:%s/%s?sslmode=verify-full' "$1" "$2" "$HOST" "$PORT" "$3"; }
{
  echo "# Generated by docker/scripts/bootstrap-secrets.sh. Do not commit."
  echo "PROD_DATABASE_URL=$(url foa_app "$(secret pg_prod_foa_app_password)" foa)"
  echo "PROD_DIRECT_URL=$(url foa_migrator "$(secret pg_prod_foa_migrator_password)" foa)"
  echo "STAGING_DATABASE_URL=$(url nonprod_app "$(secret pg_nonprod_nonprod_app_password)" foa_staging)"
  echo "STAGING_DIRECT_URL=$(url nonprod_migrator "$(secret pg_nonprod_nonprod_migrator_password)" foa_staging)"
  echo "PREVIEW_DATABASE_URL=$(url nonprod_app "$(secret pg_nonprod_nonprod_app_password)" foa_pr)"
  echo "PREVIEW_DIRECT_URL=$(url nonprod_migrator "$(secret pg_nonprod_nonprod_migrator_password)" foa_pr)"
} | write_derived "$ROOT/vercel-urls.env" root:root 0600

echo "bootstrap-secrets: done (values not shown)"
