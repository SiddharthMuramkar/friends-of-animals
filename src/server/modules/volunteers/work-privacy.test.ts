import { expect, it } from "vitest";
import { eq } from "drizzle-orm";
import { createHarness } from "@/test/harness";
import { adultApplication, openVolunteering, staffActor } from "./testing";
import { istDate } from "./domain/hours";
import { signedInOfficer } from "../privacy/requests/testing";
import { readZip } from "../privacy/requests/subject-data/read-zip";
import {
  certificate,
  volunteerHoursEntry,
  volunteerTaskAssignment,
} from "../../db/schema";

it("exports service records and generated bytes, keeps them under a legal hold, then erases them", async () => {
  const h = await createHarness();
  const person = await adultApplication(h, await openVolunteering(h));
  const volunteer = h.as(person.actor),
    manager = h.as(await staffActor(h, "community_manager"));
  await manager.approveVolunteer({ applicationId: person.applicationId });
  const task = await manager.createVolunteerTask({
    title: "Prepare outreach",
    description: "Set up activity",
  });
  if (!task.ok) throw Error("Task missing");
  await manager.publishVolunteerTask({ taskId: task.taskId });
  await manager.assignVolunteerTask({
    taskId: task.taskId,
    volunteerUserId: person.id,
  });
  const logged = await volunteer.logVolunteerHours({
    taskId: task.taskId,
    workedOn: istDate(h.clock.now()),
    minutes: 70,
    note: "Private note of my service",
  });
  if (!logged.ok) throw Error("Log missing");
  await manager.approveVolunteerHours({ entryId: logged.entryId });
  const cert = await volunteer.requestVolunteerCertificate();
  if (!cert.ok) throw Error("Cert missing");
  await h.drain();
  const officer = h.as((await signedInOfficer(h)).actor);
  const access = await volunteer.submitPrivacyRequest({
    type: "access",
    subject: { kind: "self" },
  });
  if (!access.ok) throw Error("Access missing");
  await officer.startPrivacyRequest({ id: access.requestId });
  await officer.buildSubjectExport({ id: access.requestId });
  await h.drain();
  const link = await volunteer.getPrivacyExportLink({ id: access.requestId });
  if (!link.ok) throw Error("Export missing");
  const exported = await h.storage.get(link.url);
  if (!exported.ok) throw Error("Bytes missing");
  const archive = readZip(exported.bytes);
  expect(archive.allText()).toContain("Private note of my service");
  expect(archive.allText()).toContain(cert.number);
  expect(archive.names.some((n) => n.endsWith(".pdf"))).toBe(true);
  await h.settings.set("privacy.erasureEnabled", true);
  const admin = h.as(await h.signIn(await h.seed.superAdmin()));
  const hold = await admin.placeLegalHold({
    subjectType: "user",
    subjectId: person.id,
    reason: "Preserve service evidence",
  });
  if (!hold.ok) throw Error("Hold missing");
  const erase = await volunteer.submitPrivacyRequest({
    type: "erasure",
    subject: { kind: "self" },
  });
  if (!erase.ok) throw Error("Erasure missing");
  await officer.startPrivacyRequest({ id: erase.requestId });
  const plan = await officer.previewErasure({ id: erase.requestId });
  if (!plan.ok) throw Error("Plan missing");
  expect(plan.preview.plan.categories).toContainEqual(
    expect.objectContaining({
      key: "volunteer_service",
      action: "retain",
      basis: "legal_hold",
      count: 4,
    })
  );
  await officer.executeErasure({
    id: erase.requestId,
    fingerprint: plan.preview.plan.fingerprint,
  });
  await h.drain();
  expect(
    await h.db
      .select()
      .from(certificate)
      .where(eq(certificate.id, cert.certificateId))
  ).toHaveLength(1);
  expect(
    await h.db
      .select()
      .from(volunteerHoursEntry)
      .where(eq(volunteerHoursEntry.id, logged.entryId))
  ).toHaveLength(1);
  // A separate unheld erasure should delete the same records. The existing
  // held request is completed with a partial outcome; release then file anew.
  await admin.releaseLegalHold({ holdId: hold.holdId });
  const next = await volunteer.submitPrivacyRequest({
    type: "erasure",
    subject: { kind: "self" },
  });
  if (!next.ok) throw Error("Second request missing");
  await officer.startPrivacyRequest({ id: next.requestId });
  const nextPlan = await officer.previewErasure({ id: next.requestId });
  if (!nextPlan.ok) throw Error("Plan missing");
  expect(nextPlan.preview.plan.categories).toContainEqual(
    expect.objectContaining({
      key: "volunteer_service",
      action: "delete",
      count: 4,
    })
  );
  await officer.executeErasure({
    id: next.requestId,
    fingerprint: nextPlan.preview.plan.fingerprint,
  });
  await h.drain();
  expect(
    await h.as(h.visitor()).verifyCertificate({ number: cert.number })
  ).toEqual({ outcome: "unknown" });
  expect(
    await h.db
      .select()
      .from(volunteerTaskAssignment)
      .where(eq(volunteerTaskAssignment.volunteerUserId, person.id))
  ).toHaveLength(0);
});
