import { expect, it } from "vitest";
import { eq, like } from "drizzle-orm";
import { createHarness } from "@/test/harness";
import { ambassadorApplication, auditLog, inboxItem, outbox } from "../../../db/schema";
import { ASHA, paidCompetition, participantWithEntry } from "../../privacy/requests/subject-data/testing";
import { applicationInput, openVolunteering } from "../../volunteers/testing";
import { istDate } from "../../volunteers/domain/hours";
import { signedInOfficer } from "../../privacy/requests/testing";
import { readZip } from "../../privacy/requests/subject-data/read-zip";
import { staffActor } from "../../volunteers/testing";

it("declines with a required private reason, exports the applicant's own record, expires declined rows and erases remaining records including a retained payer", async () => {
  const h = await createHarness();
  const person = await participantWithEntry(h, await paidCompetition(h), ASHA);
  const applicant = h.as(person.actor);
  const manager = h.as(await staffActor(h, "community_manager"));
  await h.settings.set("privacy.erasureEnabled", true);
  const volunteering = await applicant.applyToVolunteer(applicationInput(await openVolunteering(h)));
  if (!volunteering.ok) throw Error(volunteering.error);
  await manager.approveVolunteer({ applicationId: volunteering.applicationId });
  const task = await manager.createVolunteerTask({ title: "Service", description: "Prepare outreach materials" });
  if (!task.ok) throw Error(task.error);
  await manager.publishVolunteerTask({ taskId: task.taskId });
  await manager.assignVolunteerTask({ taskId: task.taskId, volunteerUserId: person.userId });
  const hours = await applicant.logVolunteerHours({ taskId: task.taskId, minutes: 45, workedOn: istDate(h.clock.now()) });
  if (!hours.ok) throw Error(hours.error);
  await manager.approveVolunteerHours({ entryId: hours.entryId });
  await applicant.joinCommunity({ displayName: "Asha" });
  h.clock.advance({ days: 90 });
  const submitted = await applicant.applyForAmbassador();
  if (!submitted.ok) throw Error(submitted.error);
  const applicationId = submitted.applicationId;
  const reason = "Please provide further outreach experience.";
  const decision = { applicationId, decision: "decline" as const, reason };
  expect(await manager.decideAmbassador({ ...decision, reason: "  " })).toMatchObject({ ok: false, error: "invalid_input" });
  await expect(applicant.decideAmbassador(decision)).rejects.toMatchObject({ code: "forbidden" });
  expect(await manager.decideAmbassador(decision)).toEqual({ ok: true });
  expect(await manager.decideAmbassador(decision)).toMatchObject({ ok: false, error: "invalid_transition" });
  expect((await applicant.getMyAmbassador()).application).toMatchObject({ status: "declined", declineReason: reason });
  expect((await applicant.getTimeline()).milestones.some((row) => row.kind === "ambassador")).toBe(false);
  await h.drain();
  const notices = await applicant.listInbox();
  expect(notices).toContainEqual(expect.objectContaining({ title: "Your FOA Ambassador application was declined", body: `Reason: ${reason}` }));
  expect(notices.filter(({ title }) => title === "Your FOA Ambassador application was declined")).toHaveLength(1);
  expect(h.email.sent.some(({ text }) => text.includes(reason))).toBe(false);
  expect(JSON.stringify(await h.db.select().from(ambassadorApplication))).not.toContain(reason);
  expect(JSON.stringify(await h.db.select().from(outbox).where(like(outbox.eventType, "ambassador.%")))).not.toContain(reason);
  expect(JSON.stringify(await h.db.select().from(auditLog).where(like(auditLog.action, "ambassador.%")))).not.toContain(reason);
  expect(JSON.stringify(await h.db.select().from(inboxItem).where(eq(inboxItem.userId, person.userId)))).not.toContain(reason);
  const officer = h.as((await signedInOfficer(h)).actor);
  const access = await applicant.submitPrivacyRequest({ type: "access", subject: { kind: "self" } });
  if (!access.ok) throw Error("Access missing");
  await officer.startPrivacyRequest({ id: access.requestId });
  expect(await officer.buildSubjectExport({ id: access.requestId })).toMatchObject({ ok: true });
  await h.drain();
  const link = await applicant.getPrivacyExportLink({ id: access.requestId });
  if (!link.ok) throw Error(`Export missing: ${JSON.stringify(link)}`);
  const exported = await h.storage.get(link.url);
  if (!exported.ok) throw Error("Bytes missing");
  const archive = readZip(exported.bytes);
  expect(archive.allText()).toContain('"ambassador_application"');
  expect(archive.allText()).toContain(reason);
  h.clock.advance({ seconds: 1 });
  const next = await applicant.applyForAmbassador();
  if (!next.ok) throw Error(next.error);
  await h.settings.set("retention.enforce", true);
  const worker = h.as({ kind: "system", process: "worker" });
  h.clock.advance({ days: 365 });
  const admin = h.as(await h.signIn(await h.seed.superAdmin()));
  const hold = await admin.placeLegalHold({ subjectType: "participant_profile", subjectId: person.profileId, reason: "Review pending decision" });
  if (!hold.ok) throw Error(hold.error);
  expect((await worker.runRetentionSweep()).policies.ambassadorApplications).toMatchObject({ held: 1, deleted: 0 });
  await admin.releaseLegalHold({ holdId: hold.holdId });
  expect((await worker.runRetentionSweep()).policies.ambassadorApplications).toMatchObject({ held: 0, deleted: 1 });
  const again = h.as(await h.signIn(person));
  expect((await again.getMyAmbassador()).application).toMatchObject({ id: next.applicationId, status: "submitted" });
  const freshOfficer = h.as((await signedInOfficer(h)).actor);
  const erase = await again.submitPrivacyRequest({ type: "erasure", subject: { kind: "self" } });
  if (!erase.ok) throw Error(erase.error);
  await freshOfficer.startPrivacyRequest({ id: erase.requestId });
  const plan = await freshOfficer.previewErasure({ id: erase.requestId });
  if (!plan.ok) throw Error(plan.error);
  expect(await freshOfficer.executeErasure({ id: erase.requestId, fingerprint: plan.preview.plan.fingerprint })).toEqual({ ok: true });
  await h.drain();
  expect(await h.db.select().from(ambassadorApplication).where(eq(ambassadorApplication.applicantUserId, person.userId))).toEqual([]);
});
