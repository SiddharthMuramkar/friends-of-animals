/**
 * A fact FOA has not confirmed yet. Rendered visibly by <Placeholder>
 * outside production; production leaves it out.
 */
export type Placeholder = {
  readonly kind: "placeholder";
  /** Message key under common.placeholders, naming what is missing. */
  readonly key: PlaceholderKey;
};

export type PlaceholderKey =
  | "legalName"
  | "email"
  | "phone"
  | "address"
  | "registrationType"
  | "registrationNumber"
  | "pan"
  | "grievanceOfficerName"
  | "grievanceOfficerEmail"
  | "socials"
  | "feeSchool"
  | "feeIndividual";

/** Marks an organisation fact as "to be confirmed". */
export function placeholder(key: PlaceholderKey): Placeholder {
  return { kind: "placeholder", key };
}

export function isPlaceholder(value: unknown): value is Placeholder {
  return (
    typeof value === "object" &&
    value !== null &&
    (value as { kind?: unknown }).kind === "placeholder"
  );
}

/** A fact that may still be a placeholder. */
export type OrgFact<T = string> = T | Placeholder;

